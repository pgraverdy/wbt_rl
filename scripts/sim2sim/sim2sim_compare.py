#!/usr/bin/env python3
"""Isaac Sim vs MuJoCo comparison table (heading-aligned metrics) -> $DATA_ROOT/03_eval_mujoco/comparison.md

Pairs evaluations by (reference clip, checkpoint), read from each folder's inputs.txt. MuJoCo reports produced by
run_mujoco_eval.sh are already heading-aligned; Isaac Sim evaluations are used through their `yaw_aligned/` re-analysis
(`eval_analyze.py --align-yaw --out <eval dir>/yaw_aligned`), which this script creates when missing.

Usage: DATA_ROOT=<data dir> python scripts/sim2sim/sim2sim_compare.py
"""
import os
import re
import subprocess
import sys
from pathlib import Path

DATA = Path(os.environ.get("DATA_ROOT", Path(__file__).resolve().parents[2] / "data"))
ANALYZE = Path(__file__).resolve().parents[1] / "eval" / "eval_analyze.py"
PATS = {
    "resets": r"root jump > 0.3 m between steps\): (\d+)",
    "min_h": r"whole recording: ([\d.]+) m",
    "jerr": r"joint position error\s+mean [\d.]+ rad \(([\d.]+) deg\)",
    "drift": r"root displacement err mean ([\d.]+) m",
    "drift_max": r"root displacement err mean [\d.]+ m, max ([\d.]+) m",
    "z": r"root height error\s+mean ([\d.]+) m",
    "ori": r"root orientation err\s+mean ([\d.]+) deg",
    "body": r"body pos err .*? mean ([\d.]+) m",
    "yaw": r"rotated by ([+-][\d.]+) deg",
}


def parse(path: Path):
    t = path.read_text() if path.exists() else ""
    if "joint position error" not in t:
        return None
    return {k: (float(m.group(1)) if (m := re.search(p, t)) else None) for k, p in PATS.items()}


def key_of(d: Path):
    inp = (d / "inputs.txt").read_text() if (d / "inputs.txt").exists() else ""
    ref = re.search(r"reference: (\S+)", inp)
    ck = re.search(r"model_(\d+)", d.name)
    if not (ref and ck):
        return None, None
    return (re.sub(r"_stageii_trainer_input\.npz$", "", Path(ref.group(1)).name), ck.group(1)), ref.group(1)


isaac, mujoco = {}, {}
for d in sorted((DATA / "03_eval").glob("*/*/*/")):
    key, ref = key_of(d)
    if not key or not (d / "eval_recording.npz").exists():
        continue
    rep = d / "yaw_aligned" / "report.txt"
    if not rep.exists():
        (d / "yaw_aligned").mkdir(exist_ok=True)
        out = subprocess.run([sys.executable, str(ANALYZE), "--rec", str(d / "eval_recording.npz"), "--ref", ref,
                              "--out", str(d / "yaw_aligned"), "--align-yaw"], capture_output=True, text=True)
        rep.write_text(out.stdout)
    if (r := parse(rep)):
        isaac[key] = r
for d in sorted((DATA / "03_eval_mujoco").glob("*/*/*/")):
    key, _ = key_of(d)
    rep = d / "yaw_aligned" / "report.txt" if (d / "yaw_aligned" / "report.txt").exists() else d / "report.txt"
    if key and (r := parse(rep)) and r["yaw"] is not None:
        mujoco[key] = r

fmt = lambda v, s=1.0, n=1: "?" if v is None else f"{v * s:.{n}f}"
lines = ["# Isaac Sim vs MuJoCo (sim-to-sim), one rollout per simulator, heading-aligned metrics", "",
         "Generated by scripts/sim2sim/sim2sim_compare.py. Same analysis (eval_analyze.py --align-yaw) for both simulators.", "",
         "| Clip | Ckpt | Sim | Resets | Min pelvis | Joint err | Drift mean / max | Pelvis z err | Orientation | Body pos | Heading corr. |",
         "|---|---|---|---|---|---|---|---|---|---|---|"]
for key in sorted(set(isaac) | set(mujoco)):
    clip, ck = key
    for sim, r in (("Isaac Sim", isaac.get(key)), ("MuJoCo", mujoco.get(key))):
        if r is None:
            lines.append(f"| {clip} | {int(ck)} | {sim} | – | – | – | – | – | – | – | – |")
            continue
        lines.append(f"| {clip} | {int(ck)} | {sim} | {fmt(r['resets'],1,0)} | {fmt(r['min_h'],1,3)} m | {fmt(r['jerr'],1,2)}° | "
                     f"{fmt(r['drift'],100)} / {fmt(r['drift_max'],100)} cm | {fmt(r['z'],100)} cm | {fmt(r['ori'],1,1)}° | "
                     f"{fmt(r['body'],100)} cm | {fmt(r['yaw'],1,1)}° |")
lines += ["", "## MuJoCo − Isaac Sim", "", "| Clip | Ckpt | Joint err | Drift mean | Orientation | Body pos | MuJoCo falls |",
          "|---|---|---|---|---|---|---|"]
for key in sorted(set(isaac) & set(mujoco)):
    a, b = isaac[key], mujoco[key]
    lines.append(f"| {key[0]} | {int(key[1])} | {b['jerr'] - a['jerr']:+.2f}° | {(b['drift'] - a['drift']) * 100:+.1f} cm | "
                 f"{b['ori'] - a['ori']:+.1f}° | {(b['body'] - a['body']) * 100:+.1f} cm | "
                 f"{'yes' if (b['resets'] or 0) > 0 or (b['min_h'] or 1) < 0.4 else 'no'} |")
out = DATA / "03_eval_mujoco" / "comparison.md"
out.parent.mkdir(parents=True, exist_ok=True)
out.write_text("\n".join(lines) + "\n")
print("\n".join(lines))
