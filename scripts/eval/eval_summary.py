#!/usr/bin/env python3
"""Collect every Isaac Sim evaluation under $DATA_ROOT/03_eval into one markdown table ($DATA_ROOT/03_eval/summary.md).

Usage: DATA_ROOT=<data dir> python scripts/eval/eval_summary.py   (DATA_ROOT defaults to the repository's data/)
"""
import os
import re
from pathlib import Path

DATA = Path(os.environ.get("DATA_ROOT", Path(__file__).resolve().parents[2] / "data"))
EVAL = DATA / "03_eval"
PATS = {
    "clip_s": r"reference clip: \d+ frames \(([\d.]+) s\)",
    "resets": r"Resets/teleports \(root jump > 0.3 m between steps\): (\d+)",
    "min_h": r"Min root \(pelvis\) height over the whole recording: ([\d.]+) m",
    "ref_min_h": r"\(reference min ([\d.]+) m\)",
    "jerr_deg": r"joint position error\s+mean [\d.]+ rad \(([\d.]+) deg\)",
    "jworst": r"worst single joint ([\d.]+) rad",
    "drift_mean": r"root displacement err mean ([\d.]+) m",
    "drift_max": r"root displacement err mean [\d.]+ m, max ([\d.]+) m",
    "z_mean": r"root height error\s+mean ([\d.]+) m",
    "ori_mean": r"root orientation err\s+mean ([\d.]+) deg",
    "ori_max": r"root orientation err\s+mean [\d.]+ deg, max ([\d.]+) deg",
    "body_mean": r"body pos err .*? mean ([\d.]+) m",
    "body_max": r"body pos err .*? mean [\d.]+ m, max ([\d.]+) m",
}


def parse(d: Path):
    rep = d / "report.txt"
    if not rep.exists() or "joint position error" not in (txt := rep.read_text()):
        return None
    r = {k: (m.group(1) if (m := re.search(p, txt)) else "?") for k, p in PATS.items()}
    inp = (d / "inputs.txt").read_text() if (d / "inputs.txt").exists() else ""
    m = re.search(r"reference: .*/(\w+?)_stageii_trainer_input\.npz", inp)
    r["clip"] = m.group(1) if m else "?"
    ck = re.search(r"model_(\d+)", d.name)
    r["ckpt"] = ck.group(1) if ck else "?"
    r["dir"] = d.name
    r["method"] = d.parent.name                             # <retargeter>_<trainer>, e.g. gmr_holosoma_custom
    return r


def cm(x):
    return f"{float(x) * 100:.1f}" if x != "?" else "?"


rows = [r for rep in sorted(EVAL.glob("*/*/*/report.txt")) if (r := parse(rep.parent))]
latest = {(r["clip"], r["method"], r["ckpt"]): r for r in rows}   # keep the latest evaluation per (clip, method, checkpoint)
lines = [
    "# Evaluation summary (auto-generated by scripts/eval/eval_summary.py)", "",
    "One deterministic rollout per checkpoint in Isaac Sim, motion started at frame 0, scored over the clip window.", "",
    "| Clip | Method | Length | Checkpoint | Resets | Min pelvis (ref) | Joint err mean | Worst joint | Drift mean / max | Pelvis z err | Orientation mean / max | Body pos mean / max | Eval folder |",
    "|---|---|---|---|---|---|---|---|---|---|---|---|---|",
]
for (clip, method, ck), r in sorted(latest.items()):
    lines.append(
        f"| {clip} | {method} | {r['clip_s']} s | {int(ck) if ck.isdigit() else ck} | {r['resets']} | {r['min_h']} m ({r['ref_min_h']}) | "
        f"{r['jerr_deg']}° | {r['jworst']} rad | {cm(r['drift_mean'])} / {cm(r['drift_max'])} cm | {cm(r['z_mean'])} cm | "
        f"{r['ori_mean']}° / {r['ori_max']}° | {cm(r['body_mean'])} / {cm(r['body_max'])} cm | {r['dir']} |")
out = EVAL / "summary.md"
out.write_text("\n".join(lines) + "\n")
print(out)
print("\n".join(lines[4:]))
